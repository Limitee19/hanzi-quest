export function buildSeed(now = Date.now()): Vocab[] {
  return RAW.map(([hanzi, pinyin, meaning, example, exampleMeaning, level, radical]) => {
    const p = parsePinyin(pinyin)
    return {
      hanzi,
      pinyin,
      pinyinBase: p.base,
      tones: p.tones,
      meaning,
      example,
      exampleMeaning,
      level,
      radical,
      ...defaultCard(),
      due: now,
      updatedAt: now,
      createdAt: now,
    }
  })
}

export async function syncSeed(): Promise<{ added: number; total: number }> {
  const all = await db.vocab.toArray()
  const have = new Set(all.map((v) => `${v.hanzi}::${v.level}`))
  const now = Date.now()
  const missing = buildSeed(now).filter((v) => !have.has(`${v.hanzi}::${v.level}`))
  if (missing.length) await db.vocab.bulkAdd(missing)
  const total = await db.vocab.count()
  return { added: missing.length, total }
}

export function validateRow(r: Record<string, string>): string | null {
  if (!r.hanzi?.trim()) return 'hanzi kosong'
  if (!r.pinyin?.trim()) return `pinyin kosong: ${r.hanzi}`
  if (!r.meaning?.trim()) return `arti kosong: ${r.hanzi}`
  const lv = Number(r.level)
  if (!Number.isInteger(lv) || lv < 1 || lv > 6) return `level salah: ${r.hanzi}`
  return null
}
